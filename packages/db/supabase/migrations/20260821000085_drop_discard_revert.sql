-- 0085 · 폐기 되돌리기를 없앤다
--
-- 사장님: "삭제해줘 재고 수정하면 되니까"
--         "폐기 취소 기능 자체가 없는데 노출될 이유가 없지?"
--
-- 앱에서 폐기 되돌리기를 걷어냈는데 RPC 는 그대로 남아 있었다.
-- `authenticated` 실행 권한이 붙어 있으니 **로그인한 클라이언트면 누구나** 부를 수 있다.
-- 화면에 없는 기능이 API 로는 열려 있는 상태 — 그건 노출이다.
--
-- 확인한 것
--   · DB 안에서 이 함수를 부르는 곳: 없음
--   · 앱에서 부르는 곳: 없음 (useRevertDiscard 제거됨)
--   · 상쇄 이벤트 실측: 0건
--
-- 왜 입고 취소는 남기나 — **기준단가 때문이다.**
--   입고 취소는 `쓴 돈 ÷ 들어온 양`을 다시 계산해야 한다. 그 입고를 가중평균에서
--   빼지 않으면 단가가 영원히 틀리고 연결된 메뉴 원가까지 따라 틀어진다.
--   재고 수량만 고쳐서는 절대 못 되돌린다.
--   폐기는 기준단가를 건드리지 않으므로(0041) 재고 수정(E5)으로 충분하다.
--
-- ⚠ 되돌아갈 길은 남아 있다. 원장은 append-only 라 과거 상쇄 이벤트가 있으면
--   그대로 보존되고, stock_history 는 여전히 reverted 를 계산한다(입고 취소가 쓴다).
-- ════════════════════════════════════════════════════════════════

drop function if exists public.e2_discard_reverted(uuid, text);

-- 같은 이름이 다시 생기면 앱에 없는 기능이 API 로 열린다. 그때는 이 주석부터 읽게 한다.
comment on function public.e11_inbound_reverted(uuid, text) is
  '입고 취소. 재고·기준단가·추이를 함께 되돌린다 — 단가가 걸려 있어 재고 수정으로 대체할 수 없다. '
  '폐기 되돌리기(e2_discard_reverted)는 단가에 영향이 없어 0085 에서 제거했다.';

select public.assert_no_rpc_overloads();
